import { assertSchemaColumns } from './schema-validation';
import { ANALYSIS_RUNTIME_VERSIONS } from '@gist/contracts';
import { DATASOURCE_MEMORY_SCHEMA_SQL } from './memory-schema';
import { ANALYSIS_STATE_SCHEMA_SQL } from './analysis-state-schema';

/** Current schema only: no legacy table creation, conversion or history backfill. */
export const CURRENT_SCHEMA_SQL = `
      CREATE TABLE IF NOT EXISTS app_user (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, email VARCHAR(255) NOT NULL UNIQUE,
        password_hash VARCHAR(255) NOT NULL, name VARCHAR(100) NOT NULL DEFAULT '', created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
      );
      CREATE TABLE IF NOT EXISTS data_source (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(100) NOT NULL, is_local SMALLINT NOT NULL DEFAULT 0,
        created_by INTEGER REFERENCES app_user(id) ON DELETE SET NULL, description VARCHAR(255), created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
      );
      CREATE TABLE IF NOT EXISTS datasource_table_catalog (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        datasource_id INTEGER NOT NULL REFERENCES data_source(id) ON DELETE CASCADE,
        schema_name VARCHAR(63) NOT NULL DEFAULT 'public', table_name VARCHAR(63) NOT NULL,
        display_name VARCHAR(100) NOT NULL, description TEXT,
        source_type VARCHAR(20) NOT NULL CHECK(source_type IN ('preset','uploaded','external')),
        is_agent_visible BOOLEAN NOT NULL DEFAULT TRUE,
        created_by INTEGER REFERENCES app_user(id) ON DELETE SET NULL,
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
        UNIQUE(datasource_id, schema_name, table_name)
      );
      CREATE INDEX IF NOT EXISTS idx_table_catalog_agent_visible
        ON datasource_table_catalog(datasource_id, is_agent_visible);
      CREATE TABLE IF NOT EXISTS datasource_permission (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, datasource_id INTEGER NOT NULL REFERENCES data_source(id) ON DELETE CASCADE,
        user_id INTEGER NOT NULL REFERENCES app_user(id) ON DELETE CASCADE, granted_by INTEGER REFERENCES app_user(id) ON DELETE SET NULL,
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), UNIQUE(datasource_id, user_id)
      );
      CREATE TABLE IF NOT EXISTS datasource_suggestions (
        datasource_id INTEGER NOT NULL REFERENCES data_source(id) ON DELETE CASCADE, user_id INTEGER NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
        questions JSONB NOT NULL, created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), PRIMARY KEY(datasource_id, user_id)
      );
      CREATE TABLE IF NOT EXISTS password_reset_token (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id INTEGER NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
        token VARCHAR(64) NOT NULL UNIQUE, expires_at TIMESTAMPTZ NOT NULL, used_at TIMESTAMPTZ, created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
      );
      CREATE TABLE IF NOT EXISTS conversation (
        id UUID PRIMARY KEY, user_id INTEGER NOT NULL REFERENCES app_user(id) ON DELETE CASCADE, datasource_id INTEGER REFERENCES data_source(id) ON DELETE SET NULL,
        title VARCHAR(200) NOT NULL DEFAULT '新对话', created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
      );
      CREATE TABLE IF NOT EXISTS message (
        id UUID PRIMARY KEY, conversation_id UUID NOT NULL REFERENCES conversation(id) ON DELETE CASCADE,
        role VARCHAR(20) NOT NULL CHECK(role IN ('user','assistant')), content TEXT NOT NULL DEFAULT '', blocks JSONB NOT NULL DEFAULT '[]',
        llm_messages JSONB NOT NULL DEFAULT '[]', created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
      );
      CREATE INDEX IF NOT EXISTS idx_message_conversation_time ON message(conversation_id, created_at);

CREATE TABLE IF NOT EXISTS generation (
 id UUID PRIMARY KEY, user_id INTEGER NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
 conversation_id UUID NOT NULL REFERENCES conversation(id) ON DELETE CASCADE,
 request_message_id UUID NOT NULL REFERENCES message(id) ON DELETE CASCADE,
 response_message_id UUID NOT NULL REFERENCES message(id) ON DELETE CASCADE,
 status VARCHAR(20) NOT NULL CHECK(status IN ('pending','starting','running','completed','failed','cancel_requested','cancelled')),
 last_sequence INTEGER NOT NULL DEFAULT 0, error TEXT, error_code VARCHAR(64),
 idempotency_key VARCHAR(100), request_hash VARCHAR(64), reasoning_enabled BOOLEAN NOT NULL DEFAULT FALSE,
 writer_token UUID, writer_heartbeat_at TIMESTAMPTZ, cancel_requested_at TIMESTAMPTZ,
 started_at TIMESTAMPTZ, first_token_at TIMESTAMPTZ,
 model_provider VARCHAR(100) NOT NULL DEFAULT 'openai-compatible', model_name VARCHAR(200) NOT NULL DEFAULT 'gpt-4o',
 prompt_policy_version VARCHAR(64) NOT NULL DEFAULT '${ANALYSIS_RUNTIME_VERSIONS.promptPolicy}',
 toolset_version VARCHAR(64) NOT NULL DEFAULT '${ANALYSIS_RUNTIME_VERSIONS.toolset}',
 context_policy_version VARCHAR(64) NOT NULL DEFAULT '${ANALYSIS_RUNTIME_VERSIONS.contextPolicy}',
 memory_policy_version VARCHAR(64) NOT NULL DEFAULT '${ANALYSIS_RUNTIME_VERSIONS.memoryPolicy}',
 schema_context_version VARCHAR(64) NOT NULL DEFAULT '${ANALYSIS_RUNTIME_VERSIONS.schemaContext}',
 datasource_id INTEGER REFERENCES data_source(id) ON DELETE SET NULL,
 context_upper_bound TIMESTAMPTZ NOT NULL, parent_message_id UUID REFERENCES message(id) ON DELETE SET NULL,
 created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), completed_at TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS idx_generation_user_status ON generation(user_id,status);
CREATE INDEX IF NOT EXISTS idx_generation_writer_heartbeat ON generation(status,writer_heartbeat_at);
CREATE UNIQUE INDEX IF NOT EXISTS uk_generation_user_idempotency ON generation(user_id,idempotency_key) WHERE idempotency_key IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS uk_generation_conversation_active ON generation(conversation_id) WHERE status IN ('pending','starting','running','cancel_requested');
      CREATE TABLE IF NOT EXISTS outbox_event (
        id UUID PRIMARY KEY DEFAULT gen_random_uuid(), aggregate_id UUID NOT NULL, type VARCHAR(50) NOT NULL,
        payload JSONB NOT NULL, attempts INTEGER NOT NULL DEFAULT 0, next_attempt_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
        locked_at TIMESTAMPTZ, lock_token UUID, dead_lettered_at TIMESTAMPTZ,
        published_at TIMESTAMPTZ, last_error TEXT, created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
      );
      CREATE INDEX IF NOT EXISTS idx_outbox_pending ON outbox_event(next_attempt_at, created_at) WHERE published_at IS NULL;
      CREATE INDEX IF NOT EXISTS idx_outbox_generation_sequence
        ON outbox_event(aggregate_id, ((payload->>'sequence')::bigint))
        WHERE type='generation.event' AND published_at IS NULL AND dead_lettered_at IS NULL;
      CREATE TABLE IF NOT EXISTS generation_attempt (
        id UUID PRIMARY KEY DEFAULT gen_random_uuid(), generation_id UUID NOT NULL REFERENCES generation(id) ON DELETE CASCADE,
        attempt INTEGER NOT NULL, status VARCHAR(20) NOT NULL, error TEXT, writer_token UUID, received_first_delta BOOLEAN NOT NULL DEFAULT FALSE, started_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), completed_at TIMESTAMPTZ,
        UNIQUE(generation_id, attempt)
      );
      CREATE TABLE IF NOT EXISTS generation_event (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, generation_id UUID NOT NULL REFERENCES generation(id) ON DELETE CASCADE,
        user_id INTEGER NOT NULL REFERENCES app_user(id) ON DELETE CASCADE, conversation_id UUID NOT NULL,
        message_id UUID NOT NULL, sequence INTEGER NOT NULL, event_type VARCHAR(30) NOT NULL, payload JSONB NOT NULL,
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), UNIQUE(generation_id, sequence)
      );
      CREATE INDEX IF NOT EXISTS idx_generation_event_user_id ON generation_event(user_id, id);

CREATE TABLE IF NOT EXISTS conversation_turn (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  conversation_id UUID NOT NULL REFERENCES conversation(id) ON DELETE CASCADE,
  sequence INTEGER NOT NULL,
  generation_id UUID NOT NULL UNIQUE REFERENCES generation(id) ON DELETE CASCADE,
  user_message_id UUID NOT NULL REFERENCES message(id) ON DELETE CASCADE,
  assistant_message_id UUID NOT NULL REFERENCES message(id) ON DELETE CASCADE,
  status VARCHAR(20) NOT NULL CHECK(status IN ('pending','completed','failed','cancelled')),
  final_answer TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  completed_at TIMESTAMPTZ,
  UNIQUE(conversation_id, sequence)
);
CREATE INDEX IF NOT EXISTS idx_conversation_turn_history
  ON conversation_turn(conversation_id, status, sequence);

CREATE TABLE IF NOT EXISTS query_artifact (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  generation_id UUID NOT NULL REFERENCES generation(id) ON DELETE CASCADE,
  user_id INTEGER NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
  conversation_id UUID NOT NULL REFERENCES conversation(id) ON DELETE CASCADE,
  datasource_id INTEGER NOT NULL REFERENCES data_source(id) ON DELETE CASCADE,
  title VARCHAR(200) NOT NULL,
  purpose TEXT NOT NULL,
  expected_grain TEXT NOT NULL,
  expected_shape VARCHAR(20) NOT NULL CHECK(expected_shape IN ('scalar','timeseries','category','detail')),
  original_sql TEXT NOT NULL,
  executed_sql TEXT NOT NULL,
  schema_context_version VARCHAR(64) NOT NULL,
  columns_json JSONB NOT NULL,
  result_rows JSONB NOT NULL,
  returned_row_count INTEGER NOT NULL CHECK(returned_row_count >= 0),
  total_row_count BIGINT CHECK(total_row_count IS NULL OR total_row_count >= 0),
  is_limited BOOLEAN NOT NULL DEFAULT FALSE,
  result_content_hash VARCHAR(64) NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  expires_at TIMESTAMPTZ,
  result_quality JSONB,
  analysis_context JSONB
);
CREATE INDEX IF NOT EXISTS idx_query_artifact_generation ON query_artifact(generation_id, created_at);
CREATE INDEX IF NOT EXISTS idx_query_artifact_conversation ON query_artifact(conversation_id, created_at);

CREATE TABLE IF NOT EXISTS chart_artifact (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  generation_id UUID NOT NULL REFERENCES generation(id) ON DELETE CASCADE,
  query_artifact_id UUID NOT NULL REFERENCES query_artifact(id) ON DELETE CASCADE,
  user_id INTEGER NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
  conversation_id UUID NOT NULL REFERENCES conversation(id) ON DELETE CASCADE,
  datasource_id INTEGER NOT NULL REFERENCES data_source(id) ON DELETE CASCADE,
  chart_type VARCHAR(20) NOT NULL CHECK(chart_type IN ('line','bar','pie','scatter','radar','funnel')),
  title VARCHAR(200) NOT NULL,
  x_field VARCHAR(200) NOT NULL,
  y_fields JSONB NOT NULL,
  sort JSONB,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_chart_artifact_generation ON chart_artifact(generation_id, created_at);
CREATE INDEX IF NOT EXISTS idx_chart_artifact_query ON chart_artifact(query_artifact_id);



CREATE TABLE IF NOT EXISTS datasource_column_policy (
  datasource_id INTEGER NOT NULL REFERENCES data_source(id) ON DELETE CASCADE,
  schema_name VARCHAR(63) NOT NULL DEFAULT 'public',
  table_name VARCHAR(63) NOT NULL,
  column_name VARCHAR(63) NOT NULL,
  classification VARCHAR(20) NOT NULL CHECK(classification IN ('public','internal','sensitive','restricted')),
  agent_access VARCHAR(20) NOT NULL CHECK(agent_access IN ('allow','mask','deny')),
  mask_type VARCHAR(20) CHECK(mask_type IS NULL OR mask_type IN ('redact','last4','hash')),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  PRIMARY KEY(datasource_id, schema_name, table_name, column_name)
);
CREATE INDEX IF NOT EXISTS idx_column_policy_lookup
  ON datasource_column_policy(datasource_id, schema_name, table_name);

CREATE TABLE IF NOT EXISTS generation_metric (
  generation_id UUID PRIMARY KEY REFERENCES generation(id) ON DELETE CASCADE,
  llm_call_count INTEGER NOT NULL DEFAULT 0 CHECK(llm_call_count >= 0),
  tool_call_count INTEGER NOT NULL DEFAULT 0 CHECK(tool_call_count >= 0),
  sql_call_count INTEGER NOT NULL DEFAULT 0 CHECK(sql_call_count >= 0),
  input_tokens_estimated INTEGER NOT NULL DEFAULT 0 CHECK(input_tokens_estimated >= 0),
  output_tokens_estimated INTEGER NOT NULL DEFAULT 0 CHECK(output_tokens_estimated >= 0),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS generation_trace_span (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  generation_id UUID NOT NULL REFERENCES generation(id) ON DELETE CASCADE,
  name VARCHAR(64) NOT NULL,
  status VARCHAR(20) NOT NULL CHECK(status IN ('ok','error')),
  duration_ms INTEGER NOT NULL CHECK(duration_ms >= 0),
  metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_generation_trace_span_generation
  ON generation_trace_span(generation_id,created_at);

`;
export async function applyCurrentSchema(db: { query(sql: string): Promise<unknown> }): Promise<void> {
    await db.query(CURRENT_SCHEMA_SQL);
    await db.query(DATASOURCE_MEMORY_SCHEMA_SQL);
    await db.query(ANALYSIS_STATE_SCHEMA_SQL);
    await assertCurrentSchema(db);
}

export async function assertCurrentSchema(db: { query(sql: string): Promise<unknown> }): Promise<void> {
    await assertSchemaColumns(db, CURRENT_SCHEMA_SQL + DATASOURCE_MEMORY_SCHEMA_SQL + ANALYSIS_STATE_SCHEMA_SQL);
}
