interface Queryable {
    query(sql: string, values?: unknown[]): Promise<unknown>;
}

interface DemoDataOptions {
    now?: Date;
    random?: () => number;
}

const PLATFORMS = [
    { id: 1, name: '天河', owner: '张明', description: '企业级数据分析平台，提供多维度数据洞察' },
    { id: 2, name: '星河', owner: '李婷', description: '智能营销平台，支持精准用户触达' },
    { id: 3, name: '云海', owner: '王强', description: '内容管理平台，支持多渠道内容分发' },
];

const ACTIONS = ['view', 'click', 'search', 'share', 'download'];
const TARGETS = ['首页', '数据报表', '用户分析', '趋势图', '导出功能', '搜索页', '详情页', '设置页', '帮助文档', '通知中心'];
const DAY_MS = 24 * 60 * 60 * 1000;

export async function initializeDemoData(db: Queryable, options: DemoDataOptions = {}): Promise<void> {
    const now = options.now ?? new Date();
    const random = options.random ?? Math.random;

    await db.query('BEGIN');
    try {
        await db.query(`
          CREATE TABLE IF NOT EXISTS platform_info (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            name VARCHAR(50) NOT NULL,
            owner VARCHAR(50) NOT NULL,
            description VARCHAR(200),
            created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
          );
          COMMENT ON TABLE platform_info IS '平台信息维表';
          COMMENT ON COLUMN platform_info.name IS '平台名称';
          COMMENT ON COLUMN platform_info.owner IS '负责人';
          COMMENT ON COLUMN platform_info.description IS '平台描述';

          CREATE TABLE IF NOT EXISTS daily_active_stats (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            date DATE NOT NULL,
            platform_id INTEGER NOT NULL REFERENCES platform_info(id),
            dau INTEGER NOT NULL,
            new_users INTEGER NOT NULL,
            avg_duration_min NUMERIC(6,1) NOT NULL,
            UNIQUE(date, platform_id)
          );
          COMMENT ON TABLE daily_active_stats IS '平台日活统计表';
          COMMENT ON COLUMN daily_active_stats.date IS '统计日期';
          COMMENT ON COLUMN daily_active_stats.platform_id IS '平台ID';
          COMMENT ON COLUMN daily_active_stats.dau IS '日活跃用户数';
          COMMENT ON COLUMN daily_active_stats.new_users IS '新增用户数';
          COMMENT ON COLUMN daily_active_stats.avg_duration_min IS '平均使用时长(分钟)';

          CREATE TABLE IF NOT EXISTS user_behavior_log (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            user_id VARCHAR(32) NOT NULL,
            platform_id INTEGER NOT NULL REFERENCES platform_info(id),
            action VARCHAR(30) NOT NULL,
            target VARCHAR(100),
            created_at TIMESTAMPTZ NOT NULL
          );
          COMMENT ON TABLE user_behavior_log IS '用户行为明细日志';
          COMMENT ON COLUMN user_behavior_log.user_id IS '用户ID';
          COMMENT ON COLUMN user_behavior_log.platform_id IS '平台ID';
          COMMENT ON COLUMN user_behavior_log.action IS '行为类型: view/click/search/share/download';
          COMMENT ON COLUMN user_behavior_log.target IS '行为对象';
          COMMENT ON COLUMN user_behavior_log.created_at IS '行为时间';
          CREATE INDEX IF NOT EXISTS idx_user_behavior_platform_time ON user_behavior_log(platform_id, created_at);
          CREATE INDEX IF NOT EXISTS idx_user_behavior_user ON user_behavior_log(user_id);
        `);

        await db.query(
            `INSERT INTO platform_info (id, name, owner, description)
             SELECT * FROM UNNEST($1::integer[], $2::varchar[], $3::varchar[], $4::varchar[])
             ON CONFLICT (id) DO NOTHING`,
            [
                PLATFORMS.map((platform) => platform.id),
                PLATFORMS.map((platform) => platform.name),
                PLATFORMS.map((platform) => platform.owner),
                PLATFORMS.map((platform) => platform.description),
            ]
        );

        const dailyDates: string[] = [];
        const dailyPlatformIds: number[] = [];
        const dailyDau: number[] = [];
        const dailyNewUsers: number[] = [];
        const dailyDurations: number[] = [];
        const todayUtc = Date.UTC(now.getUTCFullYear(), now.getUTCMonth(), now.getUTCDate());

        for (let daysAgo = 89; daysAgo >= 0; daysAgo--) {
            const date = new Date(todayUtc - daysAgo * DAY_MS);
            const dateString = date.toISOString().slice(0, 10);
            const weekendFactor = date.getUTCDay() === 0 || date.getUTCDay() === 6 ? 0.65 : 1;

            for (const platform of PLATFORMS) {
                const noise = 0.9 + random() * 0.2;
                const baseDau = platform.id === 1 ? 12_000 : platform.id === 2 ? 8_000 : 5_000;
                const baseNewUsers = platform.id === 1 ? 300 : platform.id === 2 ? 200 : 120;
                const baseDuration = platform.id === 1 ? 25 : platform.id === 2 ? 18 : 32;

                dailyDates.push(dateString);
                dailyPlatformIds.push(platform.id);
                dailyDau.push(Math.round(baseDau * weekendFactor * (1 + (90 - daysAgo) * 0.002) * noise));
                dailyNewUsers.push(Math.round(baseNewUsers * weekendFactor * noise));
                dailyDurations.push(Number((baseDuration * (0.85 + random() * 0.3)).toFixed(1)));
            }
        }

        await db.query(
            `INSERT INTO daily_active_stats (date, platform_id, dau, new_users, avg_duration_min)
             SELECT seed.*
             FROM UNNEST($1::date[], $2::integer[], $3::integer[], $4::integer[], $5::numeric[])
               AS seed(date, platform_id, dau, new_users, avg_duration_min)
             WHERE NOT EXISTS (SELECT 1 FROM daily_active_stats)
             ON CONFLICT (date, platform_id) DO NOTHING`,
            [dailyDates, dailyPlatformIds, dailyDau, dailyNewUsers, dailyDurations]
        );

        const behaviorIds: number[] = [];
        const behaviorUserIds: string[] = [];
        const behaviorPlatformIds: number[] = [];
        const behaviorActions: string[] = [];
        const behaviorTargets: string[] = [];
        const behaviorTimestamps: string[] = [];

        for (let daysAgo = 29; daysAgo >= 0; daysAgo--) {
            const dayUtc = todayUtc - daysAgo * DAY_MS;
            for (const platform of PLATFORMS) {
                for (let sample = 0; sample < 20; sample++) {
                    behaviorIds.push(behaviorIds.length + 1);
                    behaviorUserIds.push(`U${String(Math.floor(random() * 500) + 1).padStart(5, '0')}`);
                    behaviorPlatformIds.push(platform.id);
                    behaviorActions.push(ACTIONS[Math.floor(random() * ACTIONS.length)]);
                    behaviorTargets.push(TARGETS[Math.floor(random() * TARGETS.length)]);
                    const hour = Math.floor(random() * 14) + 8;
                    const minute = Math.floor(random() * 60);
                    behaviorTimestamps.push(new Date(dayUtc + hour * 60 * 60 * 1000 + minute * 60 * 1000).toISOString());
                }
            }
        }

        await db.query(
            `INSERT INTO user_behavior_log (id, user_id, platform_id, action, target, created_at)
             SELECT seed.*
             FROM UNNEST($1::bigint[], $2::varchar[], $3::integer[], $4::varchar[], $5::varchar[], $6::timestamptz[])
               AS seed(id, user_id, platform_id, action, target, created_at)
             WHERE NOT EXISTS (SELECT 1 FROM user_behavior_log)
             ON CONFLICT (id) DO NOTHING`,
            [behaviorIds, behaviorUserIds, behaviorPlatformIds, behaviorActions, behaviorTargets, behaviorTimestamps]
        );

        await db.query(`
          SELECT setval(pg_get_serial_sequence('platform_info', 'id'), (SELECT MAX(id) FROM platform_info), true);
          SELECT setval(pg_get_serial_sequence('user_behavior_log', 'id'), (SELECT MAX(id) FROM user_behavior_log), true);
        `);
        await db.query('COMMIT');
    } catch (error) {
        await db.query('ROLLBACK');
        throw error;
    }
}
